function GetFullPurchaseList(tPurchaseList)
    if tPurchaseList == nil or #tPurchaseList == 0 then
        return
    end

    local resultList = {}

    for _, item in pairs(tPurchaseList) do
        local compList = GetAllBaseComponents(item)
        if compList ~= nil and #compList > 0 then
            for _, comp in pairs(compList) do
                table.insert(resultList, comp)
            end
        end
    end

    return resultList
end

function GetAllBaseComponents(sItemName)
    local resultList = {}
    local function decompose(item)
        local components = GetComponents(item)
        if #components == 0 then
            table.insert(resultList, item)
        else
            for _, comp in pairs(components) do
                decompose(comp)
            end
        end
    end
    decompose(sItemName)
    return resultList
end

function GetComponents(sItemName)
    return Item[sItemName] or {}
end